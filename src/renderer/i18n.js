let lang = 'ru';
export function setLang(l) { lang = TEXT[l] ? l : 'ru'; document.documentElement.lang = lang; }
export function getLang() { return lang; }

export function t(key, vars) {
  let s = (TEXT[lang] && TEXT[lang][key]) || TEXT.ru[key] || key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? String(vars[k]) : m));
  return s;
}

export function applyTexts(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-placeholder]')) el.placeholder = t(el.dataset.i18nPlaceholder);
}

export function formatTime(sec) {
  // Сначала округлить до минут, потом делить на часы: иначе 1 ч 59 мин 59 с -> «1 ч 60 мин».
  const total = Math.round(Math.max(0, Number(sec) || 0) / 60);
  const h = Math.floor(total / 60), m = total % 60;
  return h ? t('time.h', { h, m }) : t('time.m', { m: Math.max(1, m) });
}
